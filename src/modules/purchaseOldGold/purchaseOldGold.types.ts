import { Types } from "mongoose";

/** Which document the customer produced to prove identity. */
export type IdProofType =
  | "aadhaar"
  | "pan"
  | "voter"
  | "driving_licence"
  | "passport"
  | "other";

/**
 * `standalone` — old gold bought outright for cash; the declaration is the
 * transaction record.
 * `exchange`  — old gold taken against a new ornament; the invoice is the
 * transaction record and this document links to it via `orderId`.
 */
export type DeclarationMode = "standalone" | "exchange";

/**
 * The language this declaration was signed in — a property of the document, not
 * of whoever prints it. A shopkeeper running the app in English routinely takes
 * gold from a customer who only reads Marathi, and a reprint months later has to
 * come out in the language the customer actually put their signature under.
 *
 * Absent on records written before this field existed; clients fall back to
 * their own language setting for those, which is what they did before.
 */
export type DeclarationLanguage = "en" | "hi" | "mr" | "gu";

/** `none` covers an exchange where the customer owes the shop, not vice versa. */
export type PayoutMethod = "cash" | "online" | "none";

export type OnlinePayoutType =
  | "upi"
  | "bank_transfer"
  | "cheque"
  | "card"
  | "other";

export interface DeclarationItem {
  /**
   * Stable per-declaration key, same contract as Witness.id: ornament photos
   * are addressed by this rather than by array position, because removing the
   * first of three ornaments would otherwise silently re-point the remaining
   * two at each other's photos. Generated client-side so photos can be uploaded
   * straight after the save, and preserved on update by reconcileItems.
   */
  id?: string;
  description: string;
  grams: number;
  metalType?: string;
  purity?: string;
  ratePerGm?: number;
  amount?: number;
  /** Photos of this specific ornament. Never accepted from the client body —
   *  they arrive through the multipart upload route and are carried across
   *  edits by id. */
  photos?: DeclarationPhoto[];
}

/**
 * How the shop paid the customer. Bank/UPI details are optional and captured
 * only for the shop's own audit trail.
 */
export interface DeclarationPayout {
  method: PayoutMethod;
  onlineType?: OnlinePayoutType;
  reference?: string;
  paidAt?: Date;
  bankName?: string;
  bankAccountName?: string;
  bankAccountNumber?: string;
  bankIfsc?: string;
  upiId?: string;
}

export interface DeclarationPhoto {
  url: string;
  fileId: string;
}

/** One ID document recorded on a declaration. */
export interface IdProofEntry {
  /**
   * Stable per-declaration key, same contract as Witness.id and
   * DeclarationItem.id: photos of this document are addressed by it rather than
   * by array position, because removing the first of two IDs would otherwise
   * re-point the remaining one at the wrong card's scans.
   *
   * Optional because declarations written before this field existed have none.
   */
  id?: string;
  type: IdProofType;
  number: string;
  otherLabel?: string;
  /**
   * Scans of this document — front and back of one card. Held for the shop's
   * own record only and never rendered into the printed declaration, same as
   * the witness ID proof: that PDF is shared with the customer, and a picture
   * of their Aadhaar travelling with it is a liability, not evidence.
   *
   * Never accepted from the client body — these arrive through the multipart
   * upload route and are carried across edits by id.
   */
  photos?: DeclarationPhoto[];
}

export interface Witness {
  /**
   * Stable per-declaration key, generated by the client (or backfilled on
   * write). Photos are addressed by this rather than by array position: an
   * update replaces the whole `witnesses` array, so index-addressing would
   * reassign one witness's ID proof to another the moment a row is removed.
   *
   * Optional because declarations signed before this field existed have none.
   */
  id?: string;
  name: string;
  phone?: string;
  /**
   * ID proof for this witness. Held for the shop's own record only — never
   * rendered into the printed declaration, which gets shared with the customer.
   */
  photos?: DeclarationPhoto[];
}

/**
 * The customer's details as they stood when the declaration was signed.
 * Snapshotted, not joined: editing the Customer record later must not
 * retroactively alter the contents of a signed legal document.
 */
export interface CustomerSnapshot {
  name: string;
  phone: string;
  address?: string;
  /** The customer's profile photo as it stood when the declaration was signed.
   *  Snapshotted like the name and phone beside it: the document has to keep
   *  showing the face that was on it, not whatever the profile holds today. */
  photoUrl?: string;
}

export interface PurchaseOldGold {
  _id: Types.ObjectId;
  userId: Types.ObjectId;
  customerId: Types.ObjectId;

  declarationNumber: string;
  declarationDate: Date;

  mode: DeclarationMode;
  orderId?: Types.ObjectId;

  /** See DeclarationLanguage — absent on records predating the field. */
  language?: DeclarationLanguage;

  /** Print the ornament photographs. Absent means true - see the model. */
  includePhotosOnDeclaration?: boolean;

  customerSnapshot: CustomerSnapshot;

  /** False => the goods belong to a family member, named in `familyMemberName`. */
  ownerIsSelf: boolean;
  familyMemberName?: string;

  /** Legacy singular fields, mirrored from idProofs[0] for older records. */
  idProofType: IdProofType;
  idProofNumber: string;
  idProofOtherLabel?: string;
  idProofs?: IdProofEntry[];
  hasPurchaseReceipt?: boolean;

  purchaseReceiptDetails?: string;
  noReceiptReason?: string;

  items: DeclarationItem[];
  totalGrams: number;
  totalAmount: number;

  payout: DeclarationPayout;
  photos: DeclarationPhoto[];
  witnesses: Witness[];

  /** Seller's signature as an SVG string. Absent when signed on paper. */
  customerSignature?: string;
  customerSignedAt?: Date;

  deletedAt: Date | null;

  createdAt: Date;
  updatedAt: Date;
}

